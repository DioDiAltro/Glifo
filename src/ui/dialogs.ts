/** Conferma dentro la pagina (i `confirm()` del browser non sempre sono disponibili). */
export function confirmDialog(opts: {
  title: string
  message: string
  confirmLabel: string
  cancelLabel?: string
  /** Una riga in più, più piccola, sotto il messaggio. */
  note?: string
  danger?: boolean
}): Promise<boolean> {
  return new Promise((resolve) => {
    let confirmed = false
    const dialog = dialogShell(
      opts.title,
      [
        h('p', { class: 'confirm-message' }, opts.message),
        opts.note ? h('p', { class: 'field-help confirm-note' }, opts.note) : null,
        h(
          'div',
          { class: 'dialog-actions' },
          h('button', { class: 'btn', attrs: { type: 'button' }, on: { click: () => dialog.close() } }, opts.cancelLabel ?? T.cancel),
          h(
            'button',
            {
              class: `btn ${opts.danger ? 'btn-danger' : 'btn-primary'}`,
              attrs: { type: 'button', autofocus: true },
              on: {
                click: () => {
                  confirmed = true
                  dialog.close()
                },
              },
            },
            opts.confirmLabel,
          ),
        ),
      ],
      'dialog-confirm',
    )
    dialog.addEventListener('close', () => resolve(confirmed))
    dialog.showModal()
  })
}

/**
 * Chiede un testo, per esempio il nome di una cartella. `check` restituisce il problema da
 * mostrare (es. «nome già usato») oppure null se va bene. Annullando si ottiene null.
 */
export function promptDialog(opts: {
  title: string
  label: string
  confirmLabel: string
  value?: string
  maxLength?: number
  check?: (value: string) => string | null
}): Promise<string | null> {
  return new Promise((resolve) => {
    let result: string | null = null
    const input = h('input', {
      class: 'prompt-input',
      attrs: { type: 'text', value: opts.value ?? '', maxlength: opts.maxLength, autocomplete: 'off', autofocus: true },
    })
    const error = h('p', { class: 'prompt-error', attrs: { role: 'alert', hidden: true } })
    const form = h(
      'form',
      {
        class: 'prompt-form',
        on: {
          submit: (ev) => {
            ev.preventDefault()
            const problem = opts.check?.(input.value) ?? null
            if (problem) {
              error.textContent = problem
              error.hidden = false
              input.focus()
              return
            }
            result = input.value
            dialog.close()
          },
        },
      },
      h('label', { class: 'prompt-label' }, h('span', {}, opts.label), input),
      error,
      h(
        'div',
        { class: 'dialog-actions' },
        h('button', { class: 'btn', attrs: { type: 'button' }, on: { click: () => dialog.close() } }, T.cancel),
        h('button', { class: 'btn btn-primary', attrs: { type: 'submit' } }, opts.confirmLabel),
      ),
    )
    input.addEventListener('input', () => (error.hidden = true))
    const dialog = dialogShell(opts.title, [form], 'dialog-prompt')
    dialog.addEventListener('close', () => resolve(result))
    dialog.showModal()
    input.select()
  })
}

